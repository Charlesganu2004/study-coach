// Browser presentation checks use a clearly marked answer fixture. The separate
// prototype receipt records a real provider call through the Rust service.
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
import { mkdtemp, readFile, mkdir, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const executable = process.env.STUDY_COACH_APP || path.join(root, 'target', 'debug', process.platform === 'win32' ? 'study-coach-app.exe' : 'study-coach-app');
const temporary = await mkdtemp(path.join(os.tmpdir(), 'study-coach-ui-'));
const dataDir = path.join(temporary, 'data');
const evidence = process.env.STUDY_COACH_UI_EVIDENCE || path.join(temporary, 'screenshots');
await mkdir(evidence, { recursive: true });
const environment = { ...process.env };
delete environment.GROQ_API_KEY;
delete environment.NVIDIA_API_KEY;
const child = spawn(executable, ['--data-dir', dataDir, '--no-open'], { env: environment, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
let browser;
const failures = [];
try {
  const url = await new Promise((resolve, reject) => {
    let output = '';
    const timeout = setTimeout(() => reject(new Error('Local app did not start within 20 seconds.')), 20000);
    child.on('error', reject);
    child.on('exit', code => { clearTimeout(timeout); reject(new Error(`Local app exited early (${code}).`)); });
    child.stdout.on('data', data => {
      output += data.toString();
      const match = output.match(/http:\/\/127\.0\.0\.1:\d+\//);
      if (match) { clearTimeout(timeout); resolve(match[0]); }
    });
  });
  browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { channel: 'msedge' } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce', deviceScaleFactor: 2 });
  const page = await context.newPage();
  page.on('pageerror', error => failures.push(error.message));
  await page.goto(url);
  await page.getByText('Connection needed', { exact: true }).waitFor();
  assert.equal(await page.locator('#note-count').innerText(), '12');
  assert.match(await readFile(path.join(dataDir, '.env'), 'utf8'), /GROQ_API_KEY=\s*\nNVIDIA_API_KEY=\s*$/);
  await page.screenshot({ path: path.join(evidence, 'desktop-first-launch.png'), fullPage: true });
  const badInput = await page.evaluate(async () => {
    const state = await (await fetch('/api/state')).json();
    const response = await fetch('/api/answer', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Coach-Token': state.csrf_token }, body: JSON.stringify({ question: '???' }) });
    return { status: response.status, body: await response.json() };
  });
  assert.equal(badInput.status, 200);
  assert.equal(badInput.body.output.status, 'clarify');
  assert.equal(badInput.body.local_response, true);
  await page.locator('.nav-item[data-page="history"]').click();
  await page.getByText(/Nothing saved yet/).waitFor();
  await page.locator('.nav-item[data-page="notes"]').click();
  const sourceText = '<script>window.untrustedSourceExecuted=true</script>\nA small example can explain a big idea.';
  await page.locator('#note-title').fill('Browser safety notes');
  await page.locator('#note-text').fill(sourceText);
  await page.locator('#save-note').click();
  await page.getByText('Source saved. It will be included with your next question.').waitFor();
  assert.equal(await page.locator('#note-count').innerText(), '13');
  assert.equal(await page.evaluate(() => Boolean(window.untrustedSourceExecuted)), false);
  await page.reload();
  await page.locator('#note-count').filter({ hasText: '13' }).waitFor();
  await page.locator('.nav-item[data-page="notes"]').click();
  await page.locator('#note-file').setInputFiles({ name: 'Imported study notes.md', mimeType: 'text/markdown', buffer: Buffer.from('A useful study question can be answered from its source material.\n', 'utf8') });
  assert.equal(await page.locator('#note-title').inputValue(), 'Imported study notes');
  await page.locator('#save-note').click();
  await page.locator('#note-count').filter({ hasText: '14' }).waitFor();
  const imported = page.locator('.note-detail').filter({ hasText: 'Imported study notes' });
  await imported.locator('summary').click();
  page.once('dialog', dialog => dialog.accept());
  await imported.getByRole('button', { name: 'Remove source' }).click();
  await page.locator('#note-count').filter({ hasText: '13' }).waitFor();
  await page.locator('.nav-item[data-page="settings"]').click();
  const dummy = 'ui-fixture-only-not-a-provider-credential-832649';
  await page.locator('#groq-key').fill(dummy);
  await page.locator('#save-settings').click();
  await page.getByText(/Connection saved locally/).waitFor();
  assert.equal(await page.locator('#groq-key').inputValue(), '');
  assert.equal(await page.locator('#groq-key-state').innerText(), 'Saved');
  const state = await (await page.request.get(`${url}api/state`)).json();
  assert.equal(JSON.stringify(state).includes(dummy), false);
  await page.locator('.nav-item[data-page="study"]').click();
  await page.locator('#question').fill('What is a unit test?');
  await page.route('**/api/answer', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ output: { status: 'answer', answer: 'A unit test checks one function in isolation.\nBrowser presentation fixture; not an evaluation result.', citations: [{ source_id: 'S3', quote: 'A unit test checks one function in isolation.' }] }, model: 'openai/gpt-oss-120b', latency_ms: 850 }) }));
  await page.locator('#ask-button').click();
  await page.locator('#answer-text').getByText(/A unit test checks/).waitFor();
  assert.equal(await page.locator('.citation blockquote').innerText(), 'A unit test checks one function in isolation.');
  assert.equal(await page.locator('#ask-button').isEnabled(), true);
  await page.screenshot({ path: path.join(evidence, 'desktop-answer-fixture.png'), fullPage: true });
  await page.unroute('**/api/answer');
  await page.route('**/api/answer', route => route.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: 'Provider HTTP 429: free-tier quota or rate limit reached.' }) }));
  await page.locator('#ask-button').click();
  await page.locator('#answer-error').getByText(/quota or rate limit/).waitFor();
  assert.equal(await page.locator('#ask-button').isEnabled(), true);
  await page.unroute('**/api/answer');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(evidence, 'phone-study.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.locator('.nav-item[data-page="settings"]').click();
  await page.screenshot({ path: path.join(evidence, 'phone-connections.png'), fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(() => Boolean(document.activeElement?.matches('button,a,input,select,textarea,summary'))), true);
  assert.equal(await page.locator('#motion-toggle').isDisabled(), true);
  assert.equal(await page.locator('.knowledge-cube').evaluate(node => getComputedStyle(node).animationName), 'none');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.waitForFunction(() => !document.getElementById('motion-toggle').disabled);
  await page.locator('.nav-item[data-page="study"]').click();
  const transforms = await page.locator('.knowledge-cube').evaluate(async node => {
    const before = getComputedStyle(node).transform;
    await new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    return [before, getComputedStyle(node).transform];
  });
  assert.notEqual(transforms[0], transforms[1]);
  assert.equal(await page.locator('#depth-field').evaluate(node => node.width >= innerWidth * 2), true);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.mouse.move(1150, 330);
  await page.screenshot({ path: path.join(evidence, 'desktop-dimensional-ui.png'), fullPage: true });
  await page.locator('#motion-toggle').click();
  assert.equal(await page.locator('#motion-toggle').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('.knowledge-cube').evaluate(node => getComputedStyle(node).animationName), 'none');
  await page.reload();
  await page.waitForFunction(() => document.body.classList.contains('motion-off'));
  assert.equal(await page.locator('#motion-toggle').getAttribute('aria-pressed'), 'true');
  assert.deepEqual(failures, []);
  await writeFile(path.join(evidence, 'ui-verification.json'), JSON.stringify({ checks: ['fresh setup', 'private blank credentials', 'source persistence', 'source text inert', 'Markdown import', 'source removal', 'history empty state', 'dummy key saved without readback', 'local nonsense handling', 'answer fixture rendering', 'quota error fixture', '390px overflow', 'keyboard focus', 'no browser exceptions', 'system reduced motion respected', '3D transform changes during animation', 'high density canvas', 'motion toggle persists after reload'], actual_provider_call: false, screenshot_directory: evidence }, null, 2));
  console.log('PASS: 18 browser checks; real service with labelled answer/error fixtures, 3D motion and accessibility controls.');
  console.log(`Screenshots: ${evidence}`);
} finally {
  if (browser) await browser.close();
  child.kill();
}
